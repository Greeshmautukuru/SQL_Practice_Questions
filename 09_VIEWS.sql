PROBLEM6:Create a view that displays departments having more than 2 employees.
QUERY:
CREATE VIEW DEPARTMENTS_WITH_MORE_THAN_2_EMPLOYEES AS
SELECT DEPARTMENT_NAME, COUNT(*) AS EMPLOYEE_COUNT
FROM EMPLOYEE
GROUP BY DEPARTMENT_NAME
HAVING COUNT(*) > 2;
